const DICTS = { en, es, fr, zh };
const LOCALES = { en: 'en-US', es: 'es-US', fr: 'fr-FR', zh: 'zh-CN' };

export function makeT(lang) {
  const dict = DICTS[lang] || en;
  return (key, vars) => {
    let s = dict[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
  };
}

export const localeOf = (lang) => LOCALES[lang] || 'en-US';

/** "14:30" -> "2:30 PM" (or the language's convention). */
export function formatTime(hhmm, lang) {
  if (!hhmm || !/^\d{2}:\d{2}$/.test(hhmm)) return hhmm || '';
  const [h, m] = hhmm.split(':').map(Number);
  return new Intl.DateTimeFormat(localeOf(lang), { hour: 'numeric', minute: '2-digit' }).format(new Date(2000, 0, 1, h, m));
}

/** "2026-09-25" -> "Friday, September 25" (no time zone shifts). */
export function formatDate(iso, lang, opts = { weekday: 'long', month: 'long', day: 'numeric' }) {
  if (!iso || !/^\d{4}-\d{2}-\d{2}$/.test(iso)) return iso || '';
  const [y, m, d] = iso.split('-').map(Number);
  return new Intl.DateTimeFormat(localeOf(lang), opts).format(new Date(y, m - 1, d));
}

export function monthNames(lang) {
  const fmt = new Intl.DateTimeFormat(localeOf(lang), { month: 'long' });
  return Array.from({ length: 12 }, (_, i) => fmt.format(new Date(2000, i, 1)));
}
